#!/usr/bin/env python3
"""Regenerates docs/worked-flow.md from tools/trace.py output."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def trace(*args: str) -> list[str]:
    out = subprocess.check_output([sys.executable, str(ROOT / "tools" / "trace.py"), *args], text=True)
    return out.rstrip("\n").split("\n")


def from_line(lines: list[str], needle: str) -> list[str]:
    for i, ln in enumerate(lines):
        if needle in ln:
            return lines[i:]
    return lines


def block(lines: list[str]) -> str:
    return "```\n" + "\n".join(lines) + "\n```"


doc = f"""# The worked flow, as evidence

Generated by `tools/worked_flow_doc.py` from `tools/trace.py` over the section-8 example; regenerate after a change to the example or the event schema. Times are the injected clock, seconds from run start.

## Happy path — untrusted ticket, replacement within the auto limit

{block(trace())}

## Injected address in the ticket body

{block(from_line(trace("--behaviour", "inject_address"), "node.hook              n4"))}

The destination bound `destination == PIP.verified_ship_address(device_id)` fails: a denial, never a hold; the denial branch replies and logs; no shipment.

## Between the limits — hold, approval, grant redemption

{block(from_line(trace("--hold", "--trigger", "clean-ticket"), "node.hook              n4"))}

## EVS outage on the internal-effect variant

The note (no factor, run neither exposed nor delegated) is made and journaled; the reads continue; the shipment's destination resolves outside, so the run parks at it; on recovery the journal reconciles in order and the run completes.

{block(trace("--outage", "EVS", "--trigger", "clean-ticket"))}
"""
(ROOT / "docs" / "worked-flow.md").write_text(doc)
print("docs/worked-flow.md regenerated")
